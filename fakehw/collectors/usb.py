import re

from ..models.device import DeviceClass, DeviceRecord
from ._util import Clock, failure_record, hash_serial, utcnow
from .base import Collector
from .pnp import SOURCE_NAME, PnpQueryError, PnpSource, WmiPnpSource

_DEVICE_ID = re.compile(
    r"^USB\\VID_(?P<vid>[0-9A-Fa-f]{4})&PID_(?P<pid>[0-9A-Fa-f]{4})(?P<child>&[A-Za-z0-9_]+)?\\(?P<inst>.*)$"
)
_REV = re.compile(r"&REV_([0-9A-Fa-f]{4})")


class UsbCollector(Collector):
    def __init__(self, source: PnpSource | None = None, include_serials: bool = False, clock: Clock = utcnow):
        self.source = source or WmiPnpSource()
        self.include_serials = include_serials
        self.clock = clock

    def collect(self) -> list[DeviceRecord]:
        try:
            entries = self.source.query()
        except PnpQueryError as e:
            return [failure_record(DeviceClass.USB, SOURCE_NAME, str(e), self.clock)]

        records: list[DeviceRecord] = []
        for e in entries:
            did = e.get("DeviceID") or ""
            if not did.upper().startswith("USB\\VID_") or e.get("Present") is False:
                continue  # root hubs etc. have no VID/PID
            m = _DEVICE_ID.match(did)
            if m and m["child"]:
                continue  # interface/child (MI_xx, LAMPARRAY, ...) of a device; the parent record carries the IDs
            strings = {}
            for src, dst in (("Name", "name"), ("Manufacturer", "manufacturer"), ("PNPClass", "pnp_class")):
                if e.get(src):
                    strings[dst] = e[src]
            if not m:
                records.append(DeviceRecord(
                    device_class=DeviceClass.USB, source=SOURCE_NAME, strings=strings,
                    collected_at=self.clock(), errors=[f"unparsable USB device id: {did}"],
                ))
                continue
            raw = {"vendor_id": m["vid"].upper(), "product_id": m["pid"].upper()}
            for hid in e.get("HardwareID", []):
                r = _REV.search(hid)
                if r:
                    raw["revision"] = r.group(1).upper()
                    break
            errors = []
            if any("DESCRIPTOR_FAILURE" in h.upper() for h in e.get("HardwareID", [])):
                errors.append("device descriptor request failed")
            inst = m["inst"]
            if "&" in inst:
                strings["instance_id"] = inst  # generated by Windows, not a device serial
            elif inst:
                strings["serial"] = inst if self.include_serials else hash_serial(inst)
            records.append(DeviceRecord(
                device_class=DeviceClass.USB, source=SOURCE_NAME, raw_ids=raw, strings=strings,
                collected_at=self.clock(), errors=errors,
            ))
        return sorted(records, key=lambda r: (
            tuple(sorted(r.raw_ids.items())), r.strings.get("instance_id", ""), r.strings.get("serial", ""), r.errors))
