"""Build the Windows distributions: program folder (PyInstaller), portable zip and installer (Inno Setup 6).

Usage:  python tools/build_exe.py [--no-installer]   (needs: pip install pyinstaller ".[ui]"; Inno Setup 6 for the installer)

Result in dist/:
  <CLI_NAME>/                          program folder
    <CLI_NAME>.exe                     console build: scan, kb, rules, selftest, ...
    <APP_NAME>.exe                     windowed build: opens the graphical interface directly
  <APP_NAME>-<version>-portable.zip    the same folder plus the portable marker: settings and caches stay next to the exe
  <APP_NAME>-<version>-setup.exe       installer (packaging/installer.iss); per-user, no administrator rights needed
Names come from fakehw/branding.py and the version from fakehw/__init__.py; nothing is hardcoded here.
"""

import argparse
import os
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from fakehw import __version__, branding  # noqa: E402
from fakehw.paths import PORTABLE_MARKER  # noqa: E402

# (source, destination inside the bundle) - modules locate their data relative to their own file
DATAS = [
    ("fakehw/kb/data", "fakehw/kb/data"),
    ("fakehw/rules/rules", "fakehw/rules/rules"),
]
HIDDEN_IMPORTS = ["fakehw.ui.app", "fakehw.collectors.plugins.spd"]
DOCS = ["README.md", "README.ru.md"]  # copied next to the executables

PORTABLE_TEXT = """This copy of {app} is portable: settings and downloaded databases are kept in the "data" folder next to it.
Delete this file to keep them in the user profile instead.

Эта копия {app} переносная: настройки и скачанные базы хранятся в папке «data» рядом с программой.
Удалите этот файл, чтобы хранить их в профиле пользователя.
"""

SPEC = '''# generated by tools/build_exe.py - do not edit
from PyInstaller.building.api import COLLECT, EXE, PYZ
from PyInstaller.building.build_main import Analysis

root = {root!r}
datas = [(root + "/" + src, dst) for src, dst in {datas!r}]

def analysis(script):
    return Analysis([root + "/packaging/" + script], pathex=[root], datas=datas, hiddenimports={hidden!r})

cli, gui = analysis("entry_cli.py"), analysis("entry_gui.py")
cli_exe = EXE(PYZ(cli.pure), cli.scripts, [], exclude_binaries=True, name={cli_name!r}, console=True)
gui_exe = EXE(PYZ(gui.pure), gui.scripts, [], exclude_binaries=True, name={app_name!r}, console=False)
COLLECT(cli_exe, cli.binaries, cli.datas, gui_exe, gui.binaries, gui.datas, name={cli_name!r})
'''


def release_name(kind: str) -> str:
    return f"{branding.APP_NAME}-{__version__}-{kind}"


def build_folder(dist: Path, build: Path) -> int:
    build.mkdir(exist_ok=True)
    spec = build / f"{branding.CLI_NAME}.spec"
    spec.write_text(SPEC.format(root=str(ROOT).replace("\\", "/"), datas=DATAS, hidden=HIDDEN_IMPORTS,
                                cli_name=branding.CLI_NAME, app_name=branding.APP_NAME), encoding="utf-8")
    cmd = [sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean",
           "--distpath", str(dist), "--workpath", str(build / "work"), str(spec)]
    print(" ".join(cmd))
    rc = subprocess.call(cmd)
    if rc == 0:
        for name in DOCS:
            shutil.copy2(ROOT / name, dist / branding.CLI_NAME / name)
    return rc


def write_portable_zip(folder: Path, out: Path) -> Path:
    """Zip the program folder under a top-level <APP_NAME>/ directory and add the portable marker."""
    out.parent.mkdir(parents=True, exist_ok=True)
    tmp = out.with_suffix(".zip.tmp")
    with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for path in sorted(p for p in folder.rglob("*") if p.is_file()):
            z.write(path, f"{branding.APP_NAME}/{path.relative_to(folder).as_posix()}")
        z.writestr(f"{branding.APP_NAME}/{PORTABLE_MARKER}", PORTABLE_TEXT.format(app=branding.APP_NAME))
    os.replace(tmp, out)
    return out


def find_iscc() -> str | None:
    candidates = [os.environ.get("ISCC"), shutil.which("iscc")]
    for base in (Path(os.environ.get("LOCALAPPDATA", "")) / "Programs", os.environ.get("ProgramFiles(x86)"),
                 os.environ.get("ProgramFiles")):
        if base:
            candidates.append(str(Path(base) / "Inno Setup 6" / "ISCC.exe"))
    return next((c for c in candidates if c and Path(c).is_file()), None)


def iscc_command(iscc: str, folder: Path, dist: Path) -> list[str]:
    defines = {
        "AppName": branding.APP_NAME, "AppVersion": __version__, "Tagline": branding.TAGLINE,
        "SourceDir": str(folder), "OutputDir": str(dist), "OutputName": release_name("setup"),
        "PortableMarker": PORTABLE_MARKER,
    }
    return [iscc, "/Q", *(f"/D{k}={v}" for k, v in defines.items()), str(ROOT / "packaging" / "installer.iss")]


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--no-installer", action="store_true", help="skip the Inno Setup installer")
    args = p.parse_args(argv)

    dist, build = ROOT / "dist", ROOT / "build"
    rc = build_folder(dist, build)
    if rc != 0:
        return rc
    folder = dist / branding.CLI_NAME
    print("wrote", write_portable_zip(folder, dist / f"{release_name('portable')}.zip"))

    if args.no_installer:
        return 0
    iscc = find_iscc()
    if not iscc:
        print("Inno Setup 6 not found (install it or set ISCC=<path to ISCC.exe>); installer not built.", file=sys.stderr)
        return 1
    cmd = iscc_command(iscc, folder, dist)
    print(" ".join(cmd))
    rc = subprocess.call(cmd)
    if rc == 0:
        print("wrote", dist / f"{release_name('setup')}.exe")
    return rc


if __name__ == "__main__":
    sys.exit(main())
